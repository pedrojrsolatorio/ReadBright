    public static String emojiFor(String text) {
        if (text == null) return null;
        String key = text.trim().toLowerCase(Locale.US);
        String emoji = EMOJIS.get(key);
        if (emoji != null) return emoji;
        int space = key.indexOf(' ');
        if (space > 0) return EMOJIS.get(key.substring(0, space));
        return null;
    }
